"""Legacy fixture seeder retained for parity testing.

Production chew-cycle candidates are generated by
``02b-VideoAssistedLabeling`` and reviewed in CycleReviewer. Do not add new
pipeline behavior here.
"""

from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path
from typing import Optional

import numpy as np

from .events import ChewStroke
from .mouth_shape import (
    MEDIAPIPE_AVAILABLE,
    extract_mouth_shape_from_video,
    mouth_shape_to_dataframe,
)


def _peak_indices(
    signal: np.ndarray,
    min_separation: int,
    threshold: float,
) -> list[int]:
    """Local-maximum peak indices with a minimum-separation rule."""
    if signal.size < 3:
        return []
    peaks: list[int] = []
    last = -10**9
    for i in range(1, signal.size - 1):
        v = float(signal[i])
        if v <= threshold:
            continue
        if v <= signal[i - 1] or v < signal[i + 1]:
            continue
        if (i - last) < min_separation:
            continue
        peaks.append(i)
        last = i
    return peaks


def derive_stroke_seeds(
    video_path: Path,
    min_chew_period_sec: float = 0.35,
    threshold_quantile: float = 0.5,
) -> list[ChewStroke]:
    """Run mouth-shape extraction and return candidate stroke timestamps.

    The mouth-openness signal peaks once per chewing cycle (mouth opens
    briefly between strokes for soft food; the inverse for clenched
    chews). We use a quantile-based soft threshold and a minimum-period
    rule that mirrors `BiteDetectorConfig.min_chew_period_sec`.

    Confidences in [0, 1] are derived from peak prominence above the
    threshold.
    """
    if not MEDIAPIPE_AVAILABLE:
        raise RuntimeError(
            "mediapipe is required for stroke seeding. "
            "Install with: pip install mediapipe"
        )

    frames = extract_mouth_shape_from_video(Path(video_path))
    if not frames:
        return []

    df = mouth_shape_to_dataframe(frames)
    if df.empty:
        return []

    # Use mouth_openness as the primary signal; fall back to jaw_displacement.
    signal_col = "mouth_openness"
    if signal_col not in df.columns or df[signal_col].abs().sum() == 0:
        signal_col = "jaw_displacement"

    signal = df[signal_col].to_numpy(dtype=float)
    times = df["timestamp_sec"].to_numpy(dtype=float)

    # Detrend to remove slow head-movement drift.
    if signal.size >= 5:
        kernel = np.ones(5) / 5.0
        baseline = np.convolve(signal, kernel, mode="same")
        detrended = signal - baseline
    else:
        detrended = signal - float(np.mean(signal))

    # Frame rate
    if times.size >= 2:
        dt = float(np.median(np.diff(times)))
        fps = 1.0 / dt if dt > 0 else 30.0
    else:
        fps = 30.0
    min_sep = max(1, int(round(min_chew_period_sec * fps)))

    threshold = float(np.quantile(detrended, threshold_quantile))
    peaks = _peak_indices(detrended, min_sep, threshold)
    if not peaks:
        return []

    peak_max = float(np.max(detrended))
    denom = max(peak_max - threshold, 1e-9)

    strokes: list[ChewStroke] = []
    for i in peaks:
        v = float(detrended[i])
        confidence = float(min(1.0, max(0.0, (v - threshold) / denom)))
        strokes.append(ChewStroke(
            timestamp=float(times[i]),
            confidence=confidence,
            source="auto",
        ))
    return strokes


def seed_bundle(
    bundle_dir: Path,
    overwrite: bool = False,
    min_chew_period_sec: float = 0.35,
    model_path: Optional[Path] = None,
) -> Optional[Path]:
    """Seed `stroke_seeds.json` for a session bundle.

    Looks for the first .mov/.mp4 in `bundle_dir`. If no video exists,
    returns None and writes nothing.

    When a trained visual labeler exists at `model_path` (default
    `models/visual_labeler.pth`), inference is delegated there — it
    writes both `stroke_seeds.json` and `bite_seeds.json` plus the
    `face_presence.json` track. Otherwise the heuristic mouth-openness
    peak detector below is used as a fallback.
    """
    from . import visual_labeler

    bundle_dir = Path(bundle_dir)
    out = bundle_dir / "stroke_seeds.json"
    if out.exists() and not overwrite:
        return out

    if model_path is None:
        model_path = Path("models") / visual_labeler.LAB_ONLY_MODEL_FILENAME

    if Path(model_path).exists():
        try:
            return visual_labeler.seed_bundle(
                bundle_dir,
                Path(model_path),
                overwrite=overwrite,
                min_chew_period_sec=min_chew_period_sec,
            )
        except Exception as exc:  # noqa: BLE001 — fall back to heuristic
            print(f"  visual_labeler.seed_bundle failed ({exc}); "
                  f"falling back to mouth-openness heuristic.")

    video = next(
        (p for ext in ("*.mov", "*.mp4", "*.m4v") for p in bundle_dir.glob(ext)),
        None,
    )
    if video is None:
        return None

    # Heuristic fallback. Also writes face_presence.json from the same
    # video pass so the review UI always has presence data, regardless of
    # whether the trained labeler ran.
    try:
        from .mouth_shape import (
            extract_mouth_shape_from_video,
            mouth_shape_to_dataframe,
            write_face_presence_json,
        )
        mouth_frames, presence, fps = extract_mouth_shape_from_video(
            video, return_presence=True
        )
        write_face_presence_json(bundle_dir, presence, fps)
    except Exception as exc:  # noqa: BLE001 — proceed even without presence
        print(f"  face_presence.json not written ({exc}).")
        mouth_frames = None

    if mouth_frames is None:
        strokes = derive_stroke_seeds(video, min_chew_period_sec=min_chew_period_sec)
    else:
        strokes = _strokes_from_mouth_frames(
            mouth_frames, min_chew_period_sec=min_chew_period_sec
        )

    payload = {
        "video": video.name,
        "n_strokes": len(strokes),
        "source": "heuristic",
        "strokes": [asdict(s) for s in strokes],
    }
    out.write_text(json.dumps(payload, indent=2))
    print(f"  Wrote {len(strokes)} stroke seeds (heuristic) -> {out}")
    return out


def _strokes_from_mouth_frames(
    frames,
    min_chew_period_sec: float = 0.35,
    threshold_quantile: float = 0.5,
) -> list[ChewStroke]:
    """Heuristic peak-pick from an already-extracted mouth-shape series.

    Factored out of `derive_stroke_seeds` so we can reuse the single
    video pass that also produces face_presence frames.
    """
    from .mouth_shape import mouth_shape_to_dataframe

    if not frames:
        return []
    df = mouth_shape_to_dataframe(frames)
    if df.empty:
        return []

    signal_col = "mouth_openness"
    if signal_col not in df.columns or df[signal_col].abs().sum() == 0:
        signal_col = "jaw_displacement"

    signal = df[signal_col].to_numpy(dtype=float)
    times = df["timestamp_sec"].to_numpy(dtype=float)

    if signal.size >= 5:
        kernel = np.ones(5) / 5.0
        baseline = np.convolve(signal, kernel, mode="same")
        detrended = signal - baseline
    else:
        detrended = signal - float(np.mean(signal))

    if times.size >= 2:
        dt = float(np.median(np.diff(times)))
        fps = 1.0 / dt if dt > 0 else 30.0
    else:
        fps = 30.0
    min_sep = max(1, int(round(min_chew_period_sec * fps)))

    threshold = float(np.quantile(detrended, threshold_quantile))
    peaks = _peak_indices(detrended, min_sep, threshold)
    if not peaks:
        return []

    peak_max = float(np.max(detrended))
    denom = max(peak_max - threshold, 1e-9)

    strokes: list[ChewStroke] = []
    for i in peaks:
        v = float(detrended[i])
        confidence = float(min(1.0, max(0.0, (v - threshold) / denom)))
        strokes.append(ChewStroke(
            timestamp=float(times[i]),
            confidence=confidence,
            source="auto",
        ))
    return strokes



def main():
    import argparse

    p = argparse.ArgumentParser(description="Auto-seed chew-stroke candidates from session video")
    p.add_argument("bundle", help="Session bundle directory")
    p.add_argument("--overwrite", action="store_true")
    p.add_argument("--min-period", type=float, default=0.35,
                   help="Minimum chew period in seconds (default 0.35)")
    args = p.parse_args()
    seed_bundle(Path(args.bundle), overwrite=args.overwrite, min_chew_period_sec=args.min_period)


if __name__ == "__main__":
    main()
